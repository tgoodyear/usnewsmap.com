//! `profiles.lock`: one model set per profile id, for good (13 §13.7.2, #1481).
//!
//! The release's engine index, the API and the credits page key engines by
//! `<family>/<version> <profile>`, which leaves out the `models=` digest. So
//! a profile id must always name the same model files: a different model
//! file gets a new profile id. The lock records each pinned profile's model
//! digest; `routes check` fails when a digest changes under the same id.

use std::collections::BTreeMap;
use std::path::Path;

use anyhow::{bail, Context};

use crate::Catalog;

/// The `models.lock` of each production engine with profiles, relative to
/// the directory of `profiles.lock` (`ocr/engines/`).
pub const MODEL_LOCKS: [(&str, &str); 2] = [
    ("tesseract-5.5", "tesseract/models.lock"),
    ("ndlocr-lite", "ndlocr-lite/models.lock"),
];

const HEADER: &str = "\
# Generated by `usnm-ocr-worker routes check --update-lock`; don't edit by hand.
# <engine id> <profile id> sha256:<digest of the profile's model files>
# The digest is the sha256 of the sorted lines `<name> <sha256>` from the
# engine's models.lock; a row's `models=` field is its first 12 hex digits.
# An entry never changes and is never removed: a different model file gets
# a new profile id (13 §13.7.2, #1481). `routes check` fails when a pinned
# profile's digest differs from its entry here, or when it has no entry;
# `--update-lock` adds entries for new profiles only.
";

/// `(engine id, profile id)` to the full sha256 of the profile's models.
pub type Entries = BTreeMap<(String, String), String>;

/// A `models.lock`'s pins: model name to its sha256.
pub fn pins(text: &str) -> anyhow::Result<BTreeMap<String, String>> {
    let mut out = BTreeMap::new();
    for line in text.lines().map(str::trim) {
        if line.is_empty() || line.starts_with('#') {
            continue;
        }
        let fields: Vec<&str> = line.split_whitespace().collect();
        let [name, _url, sum] = fields[..] else {
            bail!("models.lock line {line:?}: want <name> <url> <sha256>");
        };
        if !is_sha256(sum) {
            bail!("models.lock line {line:?}: {sum} isn't a lowercase sha256");
        }
        if out.insert(name.to_owned(), sum.to_owned()).is_some() {
            bail!("models.lock pins {name} twice");
        }
    }
    Ok(out)
}

/// The sha256 of the sorted lines `<name> <sha256>\n` for `models`, as the
/// worker computes a tag's `models=` (13 §13.8.1); none when one isn't pinned.
pub fn models_digest(models: &[String], pins: &BTreeMap<String, String>) -> Option<String> {
    let mut lines = models
        .iter()
        .map(|m| Some(format!("{m} {}\n", pins.get(m)?)))
        .collect::<Option<Vec<_>>>()?;
    lines.sort();
    Some(usnm_core::digest::sha256_hex(lines.concat().as_bytes()))
}

/// The digest of every profile whose models are all pinned, for the engines
/// in `model_locks` (engine id to its `models.lock` text). A production
/// engine with profiles must have a `models.lock`. Profiles with an
/// unpinned model are skipped: no image can carry that model.
pub fn profile_digests(
    catalog: &Catalog,
    model_locks: &BTreeMap<String, String>,
) -> anyhow::Result<Entries> {
    let mut out = Entries::new();
    for engine in &catalog.engine {
        let Some(text) = model_locks.get(&engine.id) else {
            if engine.production && !engine.profile.is_empty() {
                bail!(
                    "production engine {} has no models.lock in usnm_ocr_route::lock::MODEL_LOCKS",
                    engine.id
                );
            }
            continue;
        };
        let pins = pins(text).with_context(|| format!("{}'s models.lock", engine.id))?;
        for p in &engine.profile {
            if let Some(digest) = models_digest(&p.models, &pins) {
                out.insert((engine.id.clone(), p.id.clone()), digest);
            }
        }
    }
    Ok(out)
}

/// Reads the `models.lock` of each engine in [`MODEL_LOCKS`] from `dir`.
pub fn read_model_locks(dir: &Path) -> anyhow::Result<BTreeMap<String, String>> {
    MODEL_LOCKS
        .iter()
        .map(|(engine, rel)| {
            let path = dir.join(rel);
            let text = std::fs::read_to_string(&path)
                .with_context(|| format!("reading {}", path.display()))?;
            Ok(((*engine).to_owned(), text))
        })
        .collect()
}

pub fn parse(text: &str) -> anyhow::Result<Entries> {
    let mut out = Entries::new();
    for line in text.lines().map(str::trim) {
        if line.is_empty() || line.starts_with('#') {
            continue;
        }
        let fields: Vec<&str> = line.split_whitespace().collect();
        let [engine, profile, digest] = fields[..] else {
            bail!("profiles.lock line {line:?}: want <engine> <profile> sha256:<hex>");
        };
        let Some(hex) = digest.strip_prefix("sha256:").filter(|h| is_sha256(h)) else {
            bail!("profiles.lock line {line:?}: want sha256:<64 lowercase hex>");
        };
        if out
            .insert((engine.to_owned(), profile.to_owned()), hex.to_owned())
            .is_some()
        {
            bail!("profiles.lock lists {engine} {profile} twice");
        }
    }
    Ok(out)
}

pub fn render(entries: &Entries) -> String {
    let mut out = HEADER.to_owned();
    for ((engine, profile), digest) in entries {
        out.push_str(&format!("{engine} {profile} sha256:{digest}\n"));
    }
    out
}

/// Fails when a profile's digest differs from its entry in `lock`; returns
/// the profiles that have no entry yet.
fn changed_and_missing(lock: &Entries, current: &Entries) -> anyhow::Result<Entries> {
    let mut changed = Vec::new();
    let mut missing = Entries::new();
    for (key, digest) in current {
        let (engine, profile) = key;
        match lock.get(key) {
            Some(locked) if locked == digest => {}
            Some(locked) => changed.push(format!(
                "{engine} profile {profile}: locked sha256:{locked}, now sha256:{digest}"
            )),
            None => {
                missing.insert(key.clone(), digest.clone());
            }
        }
    }
    if !changed.is_empty() {
        bail!(
            "a profile's model files changed under the same profile id:\n  {}\n\
             The API and credits page key engines by profile id without the model digest, \
             so a profile id must always name the same model files. Restore the models \
             this profile pins, and add the new model files as a new profile with its own \
             id (for example `yid_jochre` beside `yid`), then run \
             `usnm-ocr-worker routes check --update-lock` (13 §13.7.2, #1481).",
            changed.join("\n  ")
        );
    }
    Ok(missing)
}

/// `routes check` without `--update-lock`: every pinned profile has an
/// unchanged entry.
pub fn verify(lock_text: &str, current: &Entries) -> anyhow::Result<()> {
    let missing = changed_and_missing(&parse(lock_text)?, current)?;
    if !missing.is_empty() {
        bail!(
            "the profile lock has no entry for {}; run `usnm-ocr-worker routes check \
             --update-lock` and commit the lock file",
            missing
                .keys()
                .map(|(e, p)| format!("{e} {p}"))
                .collect::<Vec<_>>()
                .join(", ")
        );
    }
    Ok(())
}

/// `routes check --update-lock`: the lock with entries added for new
/// profiles. A changed digest still fails, and no entry is removed.
pub fn update(lock_text: &str, current: &Entries) -> anyhow::Result<String> {
    let mut lock = parse(lock_text)?;
    lock.extend(changed_and_missing(&lock, current)?);
    Ok(render(&lock))
}

fn is_sha256(s: &str) -> bool {
    s.len() == 64 && s.bytes().all(|b| matches!(b, b'0'..=b'9' | b'a'..=b'f'))
}

#[cfg(test)]
mod tests {
    use super::*;

    const SUM_A: &str = "aaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaa";
    const SUM_B: &str = "bbbbbbbbbbbbbbbbbbbbbbbbbbbbbbbbbbbbbbbbbbbbbbbbbbbbbbbbbbbbbbbb";
    const SUM_C: &str = "cccccccccccccccccccccccccccccccccccccccccccccccccccccccccccccccc";

    fn catalog(production: bool) -> Catalog {
        let text = format!(
            r#"
schema = 1
production_licenses = ["Apache-2.0"]
[[engine]]
id = "tess"
family = "tesseract"
production = {production}
license = "Apache-2.0"
[[engine.model]]
name = "tessdata/yid.traineddata"
license = "Apache-2.0"
[[engine.model]]
name = "tessdata/eng.traineddata"
license = "Apache-2.0"
[[engine.model]]
name = "tessdata/heb.traineddata"
license = "Apache-2.0"
[[engine.profile]]
id = "yid"
models = ["tessdata/yid.traineddata"]
languages = ["yid"]
[[engine.profile]]
id = "yid+eng"
models = ["tessdata/yid.traineddata", "tessdata/eng.traineddata"]
languages = ["yid"]
[[engine.profile]]
id = "heb"
models = ["tessdata/heb.traineddata"]
languages = ["heb"]
"#
        );
        Catalog::parse(&text).unwrap()
    }

    fn models_lock(yid: &str) -> BTreeMap<String, String> {
        let text = format!(
            "# comment\n\
             tessdata/yid.traineddata https://example.org/yid {yid}\n\
             tessdata/eng.traineddata https://example.org/eng {SUM_B}\n"
        );
        [("tess".to_owned(), text)].into()
    }

    #[test]
    fn digest_matches_the_tag_digest_and_skips_unpinned_profiles() {
        let digests = profile_digests(&catalog(true), &models_lock(SUM_A)).unwrap();
        let key = |p: &str| ("tess".to_owned(), p.to_owned());
        assert_eq!(
            digests.keys().cloned().collect::<Vec<_>>(),
            [key("yid"), key("yid+eng")]
        );
        assert_eq!(
            digests[&key("yid+eng")],
            usnm_core::digest::sha256_hex(
                format!("tessdata/eng.traineddata {SUM_B}\ntessdata/yid.traineddata {SUM_A}\n")
                    .as_bytes()
            )
        );
    }

    #[test]
    fn production_engine_without_models_lock_fails() {
        let err = profile_digests(&catalog(true), &BTreeMap::new()).unwrap_err();
        assert!(err.to_string().contains("tess has no models.lock"), "{err}");
        assert!(profile_digests(&catalog(false), &BTreeMap::new())
            .unwrap()
            .is_empty());
    }

    #[test]
    fn changed_model_under_same_profile_id_fails_with_the_remedy() {
        let before = profile_digests(&catalog(true), &models_lock(SUM_A)).unwrap();
        let lock = update("", &before).unwrap();
        verify(&lock, &before).unwrap();

        let after = profile_digests(&catalog(true), &models_lock(SUM_C)).unwrap();
        for err in [
            verify(&lock, &after).unwrap_err(),
            update(&lock, &after).unwrap_err(),
        ] {
            let msg = err.to_string();
            assert!(msg.contains("tess profile yid: locked sha256:"), "{msg}");
            assert!(msg.contains("tess profile yid+eng: locked"), "{msg}");
            assert!(msg.contains("new profile with its own id"), "{msg}");
        }
    }

    #[test]
    fn new_profile_needs_update_lock_and_entries_are_kept() {
        let mut current = profile_digests(&catalog(true), &models_lock(SUM_A)).unwrap();
        let lock = update("", &current).unwrap();
        // A new id for new model files, as the rule asks.
        current.insert(("tess".into(), "yid_jochre".into()), SUM_C.into());
        let err = verify(&lock, &current).unwrap_err();
        assert!(
            err.to_string().contains("no entry for tess yid_jochre"),
            "{err}"
        );
        assert!(err.to_string().contains("--update-lock"), "{err}");

        let updated = update(&lock, &current).unwrap();
        verify(&updated, &current).unwrap();
        assert!(updated.starts_with(HEADER));
        assert!(updated.contains(&format!("tess yid_jochre sha256:{SUM_C}\n")));
        assert_eq!(update(&updated, &current).unwrap(), updated);

        // A profile dropped from the catalog keeps its entry.
        current.remove(&("tess".into(), "yid".into()));
        verify(&updated, &current).unwrap();
        assert_eq!(update(&updated, &current).unwrap(), updated);
    }

    #[test]
    fn malformed_locks_fail() {
        for bad in [
            "tess yid".to_owned(),
            "tess yid sha256:aaaa".to_owned(),
            format!("tess yid {SUM_A}"),
            format!("tess yid sha256:{}", SUM_A.to_uppercase()),
            format!("tess yid sha256:{SUM_A}\ntess yid sha256:{SUM_B}"),
        ] {
            assert!(parse(&bad).is_err(), "{bad}");
        }
        assert!(pins("tessdata/yid.traineddata https://example.org/yid").is_err());
        assert!(pins(&format!("a u {SUM_A}\na u {SUM_B}")).is_err());
    }
}
